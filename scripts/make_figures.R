## ============================================================================
## make_figures.R -- the manuscript figures that can be built from this repository
##
##   Rscript scripts/make_figures.R                  all four, from outputs/
##   Rscript scripts/make_figures.R precision        just one
##
## WHICH FIGURES THESE ARE
##
## The paper includes eighteen figures. Four come from the simulation study and are built here:
##
##   figS_scenarios.png            the kinetics profiles and onset regimes considered
##   figS_recovery_grid_A4.png     parameter recovery, every scenario and parameter
##   fig7_precision.png            posterior precision against sample size
##   figS_contraction_onset.png    posterior contraction, by onset regime
##
## Three are schematics drawn by hand and are not generated by any script. The remaining eleven
## describe the four SARS-CoV-2 variants and need the Pillar 2 testing data, which is UKHSA data
## held under agreement and is not distributed here. Their code ships in scripts/paper_outputs.R
## and runs unchanged for anyone who obtains the data: figure3(), figure4(), figure5(),
## figure4_priors(), figure_corr(), figure_pairs(), figure_prior_posterior(), figure_phase_ppc().
## So every figure in the paper is reproducible from this code; eleven of them are gated on data
## rather than on anything missing here.
##
## WHERE THE ANALYSIS WINDOW COMES FROM
##
## paper_outputs.R was written against a working directory layout in which each scenario's window
## was looked up in a recorded table, falling back to a scan of working files and then to a flat
## 40,000 draws. Neither the table nor the working files exist in a clean clone, so that fallback
## would silently apply the wrong window to every scenario -- the failure its own comments warn
## about. sim_window() is therefore replaced below with one that reads the window from the chain,
## which is where it belongs: fit_model.R records x$analysis_from, the draw after the final
## covariance adaptation.
## ============================================================================
WHICH   <- commandArgs(trailingOnly = TRUE)
OUT_DIR <- Sys.getenv("FIG_OUT",     "figures")
SIM_IN  <- Sys.getenv("FIG_SIM_DIR", "outputs")
TAG_IN  <- Sys.getenv("FIG_SIM_TAG", "i1")
FAM     <- c("A", "B", "C", "D", "E", "F")

suppressWarnings(suppressMessages(source("scripts/paper_outputs.R")))
use_form("incidence")
dir.create(OUT_DIR, showWarnings = FALSE, recursive = TRUE)

## Replace the window lookup. Assigned into the global environment so that every function in
## paper_outputs.R that consults sim_window() -- recovery_draws, precision_table,
## recovery_summary_table -- picks this up instead. Returns a NUMBER OF DRAWS counted back from
## the end, which is what the callers expect.
sim_window <- function(scenario, ...) {
  f <- chain_file(scenario, TAG_IN, SIM_IN)
  if (is.null(f))
    stop("no chain for ", scenario, " in ", SIM_IN, " with tag '", TAG_IN,
         "'. Fit the scenarios first: Rscript run_all.R simulations", call. = FALSE)
  o  <- readRDS(f)
  fl <- max(which(!is.na(o$MCMC_posteriors[, 1])))
  st <- if (!is.null(o$x$analysis_from)) as.integer(o$x$analysis_from)
        else as.integer(max(o$x$cov_start) + 1L)
  rm(o); invisible(gc(verbose = FALSE))
  max(fl - st + 1L, 1L)
}
assign("sim_window", sim_window, envir = globalenv())

have <- FAM[vapply(FAM, function(L)
  all(vapply(paste0(L, 0:3), function(s) !is.null(chain_file(s, TAG_IN, SIM_IN)), logical(1))),
  logical(1))]
cat(sprintf("scenario families with all four rungs present in %s (tag '%s'): %s\n",
            SIM_IN, TAG_IN, if (length(have)) paste(have, collapse = " ") else "none"))

FIGS <- list(
  scenarios = list(
    file = "figS_scenarios.png",
    needs_chains = FALSE,
    build = function(f) figure_scenarios(families = FAM, file = f)),
  ## layout = "tall" is the A4 portrait arrangement the manuscript uses, as the filename says;
  ## the default "wide" gives a landscape grid. Note this one takes `tags` (a vector, one per
  ## chain) where figure_precision and figure_contraction take `tag` (one string) -- passing the
  ## wrong name here works only by R's partial matching, which is not something to rely on.
  recovery = list(
    file = "figS_recovery_grid_A4.png",
    needs_chains = TRUE,
    build = function(f) figure_recovery_grid(families = have, dir = SIM_IN, tags = TAG_IN,
                                            layout = "tall", n_last = NULL, file = f)),
  precision = list(
    file = "fig7_precision.png",
    needs_chains = TRUE,
    build = function(f) figure_precision(families = have, dir = SIM_IN, tag = TAG_IN,
                                         n_last = NULL, file = f)),
  contraction = list(
    file = "figS_contraction_onset.png",
    needs_chains = TRUE,
    build = function(f) figure_contraction(families = have, dir = SIM_IN, tag = TAG_IN,
                                          n_last = NULL, y_axis = "onset", file = f)))

want <- if (length(WHICH)) tolower(WHICH) else names(FIGS)
bad  <- setdiff(want, names(FIGS))
if (length(bad)) stop("unknown figure: ", paste(bad, collapse = ", "),
                      "\nvalid: ", paste(names(FIGS), collapse = " "))

ok <- 0L; failed <- character(0)
for (k in want) {
  spec <- FIGS[[k]]
  f <- file.path(OUT_DIR, spec$file)
  if (spec$needs_chains && !length(have)) {
    cat(sprintf("\n-- %s: skipped, no fitted scenarios in %s --\n", k, SIM_IN))
    cat("   Fit them first: Rscript run_all.R simulations\n")
    failed <- c(failed, k); next
  }
  cat(sprintf("\n-- %s -> %s --\n", k, f))
  r <- try(spec$build(f), silent = TRUE)
  if (inherits(r, "try-error")) {
    cat(sprintf("   FAILED: %s", as.character(r)))
    failed <- c(failed, k)
  } else if (file.exists(f)) {
    cat(sprintf("   written, %.0f KB\n", file.info(f)$size / 1024))
    ok <- ok + 1L
  } else {
    cat("   the builder returned without error but wrote no file\n")
    failed <- c(failed, k)
  }
  invisible(gc(verbose = FALSE))
}
cat(sprintf("\n%d of %d figures written to %s/%s\n", ok, length(want), OUT_DIR,
            if (length(failed)) sprintf(" (failed: %s)", paste(failed, collapse = " ")) else ""))
quit(status = if (length(failed)) 1L else 0L)
